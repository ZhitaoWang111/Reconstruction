"""Run DualCraft on the senior's 50-object evaluation bundle (``dualcraft_main50_inputs``),
one object after another, and record each object's wall time and token use.

Runs on the DualCraft server, from the DualCraft repository, detached::

    cd /mnt/data/usr/wzt/submodules/dualcraft/dual-craft
    DISPLAY=:99 PYTHONPATH=src setsid nohup .venv/bin/python <this file> <bundle> <out> \\
        > <out>/batch.log 2>&1 < /dev/null &

Per object the command is the bundle README's, with the model swapped (the README runs
``--provider deepseek --model deepseek-v41`` on a tunnel we cannot reach)::

    dualcraft.agent.run.cli --blueprint objects/<ds>/<id>/prompt.json
      --image objects/<ds>/<id>/reference/photo_0.png
      --reference-manifest objects/<ds>/<id>/reference_manifest.json
      --require-appearance-attempt --geometry-turn-cap 8 --max-turns 20
      --blender --force --blender-close-after-run --blender-executable <blender>
      --provider openai --model <model> --thinking high
      --label <ds>_<id> --data-dir <out>/runs/<ds>_<id>

It goes through ``dualcraft_cli_launcher.py`` (beside this file), which leaves the CLI
as it is but prices a relay route id such as ``七牛云/coding-openai/gpt-6-astra`` like
``gpt-6-astra`` (so cost.json is written and ``--max-cost-usd`` holds) and logs every
model response's raw usage (reasoning tokens included) to ``usage.jsonl``.

The bundle is used as given except for one file: 38 manifests name
``reference/studio_environment.hdr``, which the bundle leaves out.  DualCraft's observe
loads it into Blender, so the run cannot observe without it.  It is generated by
DualCraft's own ``utils.render.environment.ensure_environment_file`` (deterministic; the
same bytes as the 10-19 run's copy, sha256 be1ffa48...) into a copy of the bundle under
``<out>/bundle``; the original bundle is not touched.

Output, under ``<out>``::

    bundle/                          the copy the runs read
    runs/<ds>_<id>/                  --data-dir: DualCraft's records, cache/runs/... staging
    runs/<ds>_<id>/run.log           the CLI's stdout + stderr
    runs/<ds>_<id>/usage.jsonl       one line per model response (raw usage)
    results.json                     state + per-object results, rewritten after each object
    results.csv                      the same, one row per object

Per object: exit code, wall seconds, turns, tokens (input, cached, uncached, output,
reasoning, total) from usage.jsonl, cost and tokens from DualCraft's cost.json as a check,
and whether a model.urdf was published.  A rerun skips objects that finished with exit 0
(``--retry-failed`` reruns the others; they get a fresh data dir with an ``_r<k>`` suffix).
"""
from __future__ import annotations

import argparse
import csv
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import shutil
import signal
import socket
import subprocess
import sys
import time

HERE = Path(__file__).resolve().parent
LAUNCHER = HERE / "dualcraft_cli_launcher.py"
DEFAULT_MODEL = "七牛云/coding-openai/gpt-6-astra"
HDR_NAME = "studio_environment.hdr"
CSV_FIELDS = ["dataset", "id", "label", "attempt", "exit", "seconds", "turns", "responses",
              "input_tokens", "cached_tokens", "uncached_tokens", "output_tokens",
              "reasoning_tokens", "total_tokens", "cost_usd", "model_urdf", "error"]


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def write_json(path: Path, data: dict) -> None:
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    tmp.replace(path)


def free_port(start: int) -> int:
    for port in range(start, start + 500):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            if s.connect_ex(("127.0.0.1", port)) != 0:
                return port
    raise RuntimeError(f"no free port from {start}")


def prepare_bundle(source: Path, target: Path) -> dict:
    """Copy the bundle once and add the studio environment file where a manifest names it."""
    if not target.exists():
        shutil.copytree(source, target)
    from utils.render.environment import ensure_environment_file   # DualCraft's own generator

    added = {}
    for manifest_path in sorted(target.glob("objects/*/*/reference_manifest.json")):
        manifest = json.loads(manifest_path.read_text())
        name = manifest.get("environment_hdr")
        if not name:
            continue
        hdr = (manifest_path.parent / name).resolve()
        if not hdr.is_relative_to(manifest_path.parent.resolve()):
            raise ValueError(f"{manifest_path}: environment_hdr points outside the object: {name}")
        added[str(manifest_path.parent.relative_to(target))] = ensure_environment_file(hdr)
    return added


def usage_totals(path: Path) -> dict:
    keys = {"input_tokens": "prompt_tokens", "cached_tokens": "cached_tokens",
            "output_tokens": "candidates_tokens", "reasoning_tokens": "reasoning_tokens",
            "total_tokens": "total_tokens"}
    totals = {k: 0 for k in keys} | {"responses": 0, "models": []}
    if not path.is_file():
        return totals
    models = set()
    for line in path.read_text().splitlines():
        try:
            entry = json.loads(line)
        except ValueError:
            continue
        usage = entry.get("usage") or {}
        totals["responses"] += 1
        if entry.get("model"):
            models.add(entry["model"])
        for out, key in keys.items():
            if isinstance(usage.get(key), int):
                totals[out] += usage[key]
    totals["uncached_tokens"] = totals["input_tokens"] - totals["cached_tokens"]
    totals["models"] = sorted(models)
    return totals


def run_artifacts(data_dir: Path) -> dict:
    """What DualCraft left: the published record (model.urdf) or the staging of a stopped run."""
    costs = sorted(data_dir.glob("records/*/revisions/*/cost.json")) or \
        sorted(data_dir.glob("cache/runs/*/staging/*/cost.json"))
    cost = json.loads(costs[-1].read_text()) if costs else None
    # 45fc1b10 publishes model.urdf + assets/ by materializing the record under cache/
    # (records/<rec>/revisions/<rev>/ keeps cost.json, traces, model.py, renders).
    urdfs = sorted(data_dir.glob("cache/record_materialization/*/model.urdf")) or \
        sorted(data_dir.glob("records/*/revisions/*/model.urdf"))
    trajectories = sorted(data_dir.glob("records/*/revisions/*/traces/trajectory.jsonl*")) or \
        sorted(data_dir.glob("cache/runs/*/staging/*/traces/trajectory.jsonl*"))
    turns = None
    if trajectories:
        path = trajectories[-1]
        text = (subprocess.run(["zstd", "-dc", str(path)], capture_output=True).stdout.decode()
                if path.suffix == ".zst" else path.read_text())
        turns = sum(1 for line in text.splitlines() if '"type": "turn_metrics"' in line)
    return {
        "model_urdf": str(urdfs[-1]) if urdfs else None,
        "turns": turns,
        "cost_usd": round(cost["all_in_total"]["costs_usd"]["total"], 4) if cost else None,
        "cost_json_tokens": cost["all_in_total"]["tokens"] if cost else None,
    }


def run_one(args, bundle: Path, entry: dict, data_dir: Path) -> dict:
    ds, oid = entry["dataset"], entry["id"]
    obj = bundle / "objects" / ds / oid
    data_dir.mkdir(parents=True, exist_ok=True)
    usage_log = data_dir / "usage.jsonl"
    usage_log.unlink(missing_ok=True)
    port = free_port(args.port_base)
    command = [
        sys.executable, str(LAUNCHER),
        "--blueprint", str(obj / "prompt.json"),
        "--image", str(obj / "reference" / "photo_0.png"),
        "--reference-manifest", str(obj / "reference_manifest.json"),
        "--require-appearance-attempt",
        "--geometry-turn-cap", str(args.geometry_turn_cap),
        "--max-turns", str(args.max_turns),
        "--blender", "--force", "--blender-close-after-run",
        "--blender-executable", args.blender,
        "--provider", "openai", "--model", args.model, "--thinking", args.thinking,
        "--label", f"{ds}_{oid}",
        "--data-dir", str(data_dir),
    ]
    if args.max_cost_usd is not None:
        command += ["--max-cost-usd", f"{args.max_cost_usd:g}"]
    env = dict(os.environ)
    env.update({
        "PYTHONPATH": str(Path.cwd() / "src"),
        "PYTHONUNBUFFERED": "1",
        "BLENDER_PORT": str(port),
        "DUALCRAFT_BLENDER_RUNTIME_DIR": f"/tmp/dualcraft-blender-main50-{ds}_{oid}",
        "URDF_COMPILE_TIMEOUT_SECONDS": "600",
        "DUALCRAFT_USAGE_LOG": str(usage_log),
    })
    (data_dir / "command.json").write_text(json.dumps(
        {"argv": command, "blender_port": port, "cwd": str(Path.cwd())}, indent=2, ensure_ascii=False) + "\n")
    started = time.time()
    error = None
    with open(data_dir / "run.log", "wb") as log:
        process = subprocess.Popen(command, cwd=Path.cwd(), env=env, stdout=log, stderr=subprocess.STDOUT,
                                   stdin=subprocess.DEVNULL, start_new_session=True)
        try:
            code = process.wait(timeout=args.timeout_minutes * 60)
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGTERM)
            try:
                process.wait(timeout=30)
            except subprocess.TimeoutExpired:
                os.killpg(process.pid, signal.SIGKILL)
                process.wait()
            code, error = -9, f"timed out after {args.timeout_minutes} min"
    seconds = round(time.time() - started, 1)
    if code != 0 and error is None:
        tail = (data_dir / "run.log").read_text(errors="replace").strip().splitlines()[-3:]
        error = " | ".join(line.strip() for line in tail)[-400:]
    return {"exit": code, "seconds": seconds, "error": error, "blender_port": port,
            **usage_totals(usage_log), **run_artifacts(data_dir)}


def write_outputs(out: Path, state: dict) -> None:
    write_json(out / "results.json", state)
    with open(out / "results.csv.tmp", "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=CSV_FIELDS, extrasaction="ignore")
        writer.writeheader()
        for key in state["order"]:
            row = state["objects"].get(key)
            if row:
                writer.writerow({**row, "model_urdf": bool(row.get("model_urdf"))})
    (out / "results.csv.tmp").replace(out / "results.csv")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("bundle", type=Path, help="dualcraft_main50_inputs directory")
    parser.add_argument("out", type=Path, help="output directory")
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--thinking", default="high")
    parser.add_argument("--max-turns", type=int, default=20)
    parser.add_argument("--geometry-turn-cap", type=int, default=8)
    parser.add_argument("--max-cost-usd", type=float, default=20.0,
                        help="per-object cap (DUALCRAFT_MAX_COST_USD in the server .env is 20 too)")
    parser.add_argument("--blender", default=os.environ.get("BLENDER_EXECUTABLE",
                        "/mnt/data/usr/wzt/blender/blender-4.4.0-linux-x64/blender"))
    parser.add_argument("--port-base", type=int, default=9900)
    parser.add_argument("--timeout-minutes", type=int, default=90)
    parser.add_argument("--only", default=None, help="comma-separated <ds>_<id> keys to run")
    parser.add_argument("--limit", type=int, default=None, help="run at most this many objects now")
    parser.add_argument("--retry-failed", action="store_true")
    args = parser.parse_args()

    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    bundle = out / "bundle"
    added = prepare_bundle(args.bundle.resolve(), bundle)
    manifest = json.loads((bundle / "manifest_50.json").read_text())
    entries = {f"{e['dataset']}_{e['id']}": e for e in manifest["objects"]}
    state_path = out / "results.json"
    state = json.loads(state_path.read_text()) if state_path.is_file() else {"objects": {}}
    state.update(order=list(entries), source_bundle=str(args.bundle.resolve()), hdr_added=added,
                 settings={k: getattr(args, k) for k in ("model", "thinking", "max_turns",
                           "geometry_turn_cap", "max_cost_usd", "timeout_minutes")},
                 started_at=state.get("started_at") or now())
    write_outputs(out, state)
    print(f"bundle ready: {len(entries)} objects, studio HDR added for {len(added)}", flush=True)

    wanted = args.only.split(",") if args.only else list(entries)
    ran = 0
    for key in wanted:
        if args.limit is not None and ran >= args.limit:
            break
        entry = entries[key]
        previous = state["objects"].get(key) or {}
        if previous.get("exit") == 0:
            print(f"{key}: done before, skipped", flush=True)
            continue
        if previous and not args.retry_failed:
            print(f"{key}: ran before (exit {previous.get('exit')}), skipped; --retry-failed reruns it", flush=True)
            continue
        attempt = int(previous.get("attempt", 0)) + 1
        data_dir = out / "runs" / (key if attempt == 1 else f"{key}_r{attempt}")
        print(f"{key}: start attempt {attempt} ({entry.get('estimated_label')})", flush=True)
        state["objects"][key] = {"dataset": entry["dataset"], "id": entry["id"],
                                 "label": entry.get("estimated_label"), "attempt": attempt,
                                 "data_dir": str(data_dir), "started_at": now(), "exit": None}
        write_outputs(out, state)
        try:
            result = run_one(args, bundle, entry, data_dir)
        except Exception as exc:          # a launcher failure must not stop the batch
            result = {"exit": -1, "error": f"{type(exc).__name__}: {exc}"[:400]}
        state["objects"][key].update(result, finished_at=now())
        write_outputs(out, state)
        ran += 1
        r = state["objects"][key]
        print(f"{key}: exit {r.get('exit')} in {r.get('seconds')}s, turns {r.get('turns')}, "
              f"tokens in {r.get('input_tokens')} (cached {r.get('cached_tokens')}) out {r.get('output_tokens')} "
              f"(reasoning {r.get('reasoning_tokens')}), ${r.get('cost_usd')}, urdf {bool(r.get('model_urdf'))}"
              + (f", error: {r['error']}" if r.get("error") else ""), flush=True)
    state["finished_at"] = now()
    write_outputs(out, state)
    print("BATCH_DONE", json.dumps({k: v.get("exit") for k, v in state["objects"].items()}), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
