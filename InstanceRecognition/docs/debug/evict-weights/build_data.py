"""Build data.js for the Object064 window-10 weight test page (temporary).

Run from InstanceRecognition: PYTHONPATH=. .venv/bin/python docs/debug/evict-weights/build_data.py
"""
import json, pathlib, tempfile, collections, numpy as np
from scipy.spatial import cKDTree
from src.harness.observations import Observations

SRC = pathlib.Path('artifacts/sources/scene0000_00/scene_amb3r_full100_v1')
RUN = 'harness-v14-amb3r-full100frames-20261109-1744'
OUT = pathlib.Path('docs/debug/evict-weights/data.js')
CANDS = ['0044:003','0044:005','0045:003','0045:004','0046:005','0046:006','0046:007',
         '0046:011','0047:008','0047:009','0048:005','0048:006','0049:012']
HELD_BEFORE = {'0044:003', '0044:005'}
V14_KEPT = ['0045:004', '0046:005', '0046:007', '0047:009', '0048:006']
RADII = [5, 10, 15, 20]  # cm

manifest = json.loads((SRC/'manifest.json').read_text())
mask_px = {f'{f["sequence_index"]:04d}:{i["instance_id"]:03d}': i['mask_pixels']
           for f in manifest['frames'] for i in f['instances']}
cam = lambda s: np.load(SRC/f'frames/{s:04d}.npz')['camera_to_world'][:3, 3].astype(np.float64)

with tempfile.TemporaryDirectory() as tmp:
    d = Observations(SRC, 100, tmp)
    W, H = d.items[CANDS[0]]['image_size_wh']
    P = [d.points[o] for o in CANDS]
    Cc = [np.asarray(d.items[o]['centroid']) for o in CANDS]
    T = [cam(d.items[o]['seq']) for o in CANDS]

    def part(k):
        z, y = np.median(P[k][:, 2]), np.median(P[k][:, 1])
        return ('左' if y < 5.82 else '右') + ('上门' if z > 1.5 else '下门')

    n = len(CANDS)
    theta = [[0.0]*n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            if i != j:
                m = (Cc[i] + Cc[j]) / 2
                a, b = T[i] - m, T[j] - m
                theta[i][j] = round(float(np.degrees(np.arccos(np.clip(a@b/np.linalg.norm(a)/np.linalg.norm(b), -1, 1)))), 3)

    trees = [cKDTree(p) for p in P]
    dist = [[None]*n for _ in range(n)]          # dist[i][j]: nearest distance from each point of i to cloud j
    for i in range(n):
        for j in range(n):
            if i != j:
                dist[i][j] = trees[j].query(P[i], distance_upper_bound=max(RADII)/100 + 1e-6)[0]
    hist = {}
    for r in RADII:
        hist[r] = []
        for i in range(n):
            bits = np.zeros(len(P[i]), dtype=np.int64)
            for j in range(n):
                if i != j:
                    bits |= (dist[i][j] <= r/100).astype(np.int64) << j
            c = collections.Counter(bits.tolist())
            hist[r].append(sorted([[int(k), int(v)] for k, v in c.items()], key=lambda kv: -kv[1]))

    cands = []
    for k, o in enumerate(CANDS):
        it = d.items[o]
        cands.append({
            'id': o, 'seq': it['seq'], 'frame': it['source_frame_id'], 'part': part(k),
            'held_before': o in HELD_BEFORE, 'mask_px': mask_px[o],
            'area': mask_px[o] / (W*H), 'points': len(P[k]),
            'img': f'../../../artifacts/experiments/{RUN}/evidence/{o.replace(":", "_")}.jpg',
        })

data = {'run': RUN, 'source': SRC.name, 'object': 'Object64', 'label': 'cabinet', 'window': 10,
        'image_wh': [W, H], 'limit': 5, 'radii_cm': RADII,
        'candidates': cands, 'theta': theta, 'hist': {str(r): hist[r] for r in RADII},
        'v14_kept': V14_KEPT}
OUT.write_text('// Generated by a temporary script; data for Object64, window 10 of ' + RUN + '.\n'
               'var EVICT_DATA = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'
               "if (typeof module !== 'undefined') module.exports = EVICT_DATA;\n")
print('wrote', OUT, OUT.stat().st_size, 'bytes')
for c in cands: print(c['id'], c['part'], f"{c['area']:.4f}", c['points'], 'held' if c['held_before'] else '')
print('hist sizes @10cm:', [len(h) for h in hist[10]])
